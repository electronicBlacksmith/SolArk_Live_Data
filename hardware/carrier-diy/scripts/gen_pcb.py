"""Generate carrier.kicad_pcb (placement, routing, zones, silk) with KiCad's pcbnew API.

Run from hardware/carrier with KiCad's bundled Python:
  /Applications/KiCad/KiCad.app/Contents/Frameworks/Python.framework/Versions/3.9/bin/python3 -I scripts/gen_pcb.py
Requires carrier.net (kicad-cli sch export netlist -o carrier.net carrier.kicad_sch);
net names are taken verbatim from it so DRC schematic parity matches.
"""

from __future__ import annotations

import json
import os
import sys

import pcbnew as P

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from design import BOARD, PARTS
from routes import PLACE
from gen_sch import ROOT_UUID, U
from sexp import find, parse

FPDIR = os.environ.get(
    "KICAD_FOOTPRINT_DIR",
    "/Applications/KiCad/KiCad.app/Contents/SharedSupport/footprints",
)
MM = P.FromMM
OX, OY, W, H = BOARD  # board origin and size (mm)

def V(x, y):
    return P.VECTOR2I(MM(x), MM(y))


def load_nets(path):
    with open(path) as fh:
        n = parse(fh.read())
    pins = {}
    for net in find(find(n, "nets")[0], "net"):
        name = find(net, "name")[0][1]
        for node in find(net, "node"):
            pins[(find(node, "ref")[0][1], find(node, "pin")[0][1])] = name
    return pins


def main(stage="full"):
    board = P.CreateEmptyBoard()
    board.SetCopperLayerCount(4)
    ds = board.GetDesignSettings()
    ds.SetBoardThickness(MM(1.6))
    board.SetAuxOrigin(V(OX, OY + H)) if False else ds.SetAuxOrigin(V(OX, OY + H))
    # outline
    pts = [(OX, OY), (OX + W, OY), (OX + W, OY + H), (OX, OY + H)]
    for i in range(4):
        s = P.PCB_SHAPE(board)
        s.SetShape(P.SHAPE_T_SEGMENT)
        s.SetStart(V(*pts[i]))
        s.SetEnd(V(*pts[(i + 1) % 4]))
        s.SetLayer(P.Edge_Cuts)
        s.SetWidth(MM(0.1))
        board.Add(s)

    pinnet = load_nets(os.path.join(ROOT, "carrier.net"))
    nets = {}
    for name in sorted(set(pinnet.values())):
        ni = P.NETINFO_ITEM(board, name)
        board.Add(ni)
        nets[name] = ni

    fps = {}
    for ref, (lib_id, value, fpid, lcsc, dnp, in_bom, conns, desc) in PARTS.items():
        lib, name = fpid.split(":")
        path = (
            os.path.join(ROOT, "lib", "carrier.pretty")
            if lib == "carrier"
            else os.path.join(FPDIR, lib + ".pretty")
        )
        fp = P.FootprintLoad(path, name)
        fp.SetFPID(P.LIB_ID(lib, name))
        fp.SetReference(ref)
        fp.SetValue(value)
        fp.SetPath(P.KIID_PATH("/" + ROOT_UUID + "/" + U("sym", ref)))
        fp.SetSheetname("/")
        fp.SetSheetfile("carrier.kicad_sch")
        x, y, rot, side = PLACE[ref]
        fp.SetPosition(V(x, y))
        board.Add(fp)
        if side == "B":
            fp.Flip(V(x, y), P.FLIP_DIRECTION_LEFT_RIGHT)
        fp.SetOrientationDegrees(rot)
        fp.GetField(P.FIELD_T_DESCRIPTION).SetText(desc)
        fp.SetDNP(dnp)
        fp.SetExcludedFromBOM(not in_bom)
        fp.SetExcludedFromPosFiles(dnp or not in_bom)
        if lcsc:
            fld = P.PCB_FIELD(fp, P.FIELD_T_USER, "LCSC")
            fld.SetText(lcsc)
            fld.SetVisible(False)
            fld.SetLayer(P.F_Fab if side == "F" else P.B_Fab)
            fp.Add(fld)
        # refdes live on the fab layer: the board is too dense for silk refdes
        r = fp.Reference()
        r.SetLayer(P.F_Fab if side == "F" else P.B_Fab)
        r.SetTextSize(V(0.5, 0.5))
        r.SetTextThickness(MM(0.08))
        r.SetPosition(V(x, y))
        for pad in fp.Pads():
            nm = pinnet.get((ref, pad.GetNumber()))
            if nm:
                pad.SetNet(nets[nm])
        fps[ref] = fp

    if stage == "place":
        for ref, fp in fps.items():
            bb = fp.GetCourtyard(P.F_CrtYd if fp.GetLayer() == P.F_Cu else P.B_CrtYd).BBox()
            print(
                ref,
                "CRTYD",
                f"{P.ToMM(bb.GetX()):.3f} {P.ToMM(bb.GetY()):.3f} "
                f"{P.ToMM(bb.GetRight()):.3f} {P.ToMM(bb.GetBottom()):.3f}",
            )
            for pad in fp.Pads():
                p = pad.GetPosition()
                print(
                    ref,
                    pad.GetNumber(),
                    f"{P.ToMM(p.x):.3f} {P.ToMM(p.y):.3f}",
                    pad.GetNetname(),
                )
    else:
        import routes

        routes.build(board, fps, nets)
        P.ZONE_FILLER(board).Fill(board.Zones())

    out = os.path.join(ROOT, "carrier.kicad_pcb")
    P.SaveBoard(out, board)
    add_stackup(out)
    write_rules()
    print("saved", out)


# JLC04161H-7628 (4 layers, 1.6 mm, 1 oz outer / 0.5 oz inner), values from
# gsuberland/jlcpcb_autogenerated_stackups (see fix-progress.md). OSH Park ignores the
# job file and builds its own fixed 4-layer stack; nothing here depends on impedance.
STACKUP = [
    ("F.SilkS", "Top Silk Screen", None),
    ("F.Paste", "Top Solder Paste", None),
    ("F.Mask", "Top Solder Mask", '(thickness 0.01524) (material "JLCPCB Soldermask") (epsilon_r 3.8) (loss_tangent 0)'),
    ("F.Cu", "copper", "(thickness 0.035)"),
    ("dielectric 1", "prepreg", '(thickness 0.2104) (material "Nan Ya Plastics NP-155F 7628") (epsilon_r 4.4) (loss_tangent 0.02)'),
    ("In1.Cu", "copper", "(thickness 0.0152)"),
    ("dielectric 2", "core", '(thickness 1.065) (material "Nan Ya Plastics NP-155F Core") (epsilon_r 4.43) (loss_tangent 0.02)'),
    ("In2.Cu", "copper", "(thickness 0.0152)"),
    ("dielectric 3", "prepreg", '(thickness 0.2104) (material "Nan Ya Plastics NP-155F 7628") (epsilon_r 4.4) (loss_tangent 0.02)'),
    ("B.Cu", "copper", "(thickness 0.035)"),
    ("B.Mask", "Bottom Solder Mask", '(thickness 0.01524) (material "JLCPCB Soldermask") (epsilon_r 3.8) (loss_tangent 0)'),
    ("B.Paste", "Bottom Solder Paste", None),
    ("B.SilkS", "Bottom Silk Screen", None),
]


def add_stackup(path):
    """Insert the JLC stackup into (setup ...): the bundled pcbnew cannot build one."""
    with open(path) as fh:
        text = fh.read()
    if "(stackup" in text:
        raise RuntimeError("board already has a stackup block")
    rows = [
        f'(layer "{n}" (type "{t}")' + (f" {extra}" if extra else "") + ")"
        for n, t, extra in STACKUP
    ]
    block = "(stackup " + " ".join(rows) + ' (copper_finish "None") (dielectric_constraints yes))'
    key = "\t(setup\n"
    if key not in text:
        raise RuntimeError("no (setup block in saved board")
    text = text.replace(key, key + "\t\t" + block + "\n", 1)
    with open(path, "w") as fh:
        fh.write(text)


def write_rules():
    """Strictest of JLCPCB 4-layer and OSH Park 4-layer rules (tests/test_board.py)."""
    pro = os.path.join(ROOT, "carrier.kicad_pro")
    try:
        with open(pro) as fh:
            d = json.load(fh)
    except (OSError, ValueError):
        d = {}
    d.setdefault("meta", {"filename": "carrier.kicad_pro", "version": 3})
    b = d.setdefault("board", {}).setdefault("design_settings", {})
    b.setdefault("rules", {}).update(
        {
            # Each is the stricter of JLC and OSH Park 4-layer (values and URLs in tests).
            "min_clearance": 0.15,  # JLC SMD pad to pad
            "min_track_width": 0.127,  # OSH 5 mil
            "min_via_diameter": 0.46,  # OSH 10 mil drill + 2 x 4 mil ring
            "min_via_annular_width": 0.15,  # JLC PTH ring; KiCad checks vias and PTH pads
            "min_through_hole_diameter": 0.26,  # OSH 10 mil
            "min_hole_clearance": 0.3,  # JLC inner-layer PTH hole to copper
            "min_hole_to_hole": 0.5,  # JLC pad hole to hole 0.45
            "min_copper_edge_clearance": 0.4,  # OSH 15 mil
            "min_silk_clearance": 0.0,
            "min_text_height": 1.0,
            "min_text_thickness": 0.15,
            "min_microvia_diameter": 0.2,
            "min_microvia_drill": 0.1,
            "solder_mask_to_copper_clearance": 0.0,
        }
    )
    d.setdefault("net_settings", {})["classes"] = [
        {
            "name": "Default",
            "clearance": 0.15,
            "track_width": 0.2,
            "via_diameter": 0.6,
            "via_drill": 0.3,
            "microvia_diameter": 0.3,
            "microvia_drill": 0.1,
            "diff_pair_width": 0.2,
            "diff_pair_gap": 0.25,
            "diff_pair_via_gap": 0.25,
            "wire_width": 6,
            "bus_width": 12,
            "line_style": 0,
            "pcb_color": "rgba(0, 0, 0, 0.000)",
            "schematic_color": "rgba(0, 0, 0, 0.000)",
            "priority": 2147483647,
        }
    ]
    with open(pro, "w") as fh:
        json.dump(d, fh, indent=2)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "full")
